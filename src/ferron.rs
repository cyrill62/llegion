//! Ferron configuration (`ferron.kdl`) for exposing Ollama over HTTPS with bearer-token auth.

use std::path::PathBuf;

use crate::config::{Settings, TlsMode};

pub fn config_path() -> PathBuf {
    crate::config::config_dir().join("ferron.kdl")
}

fn domain(settings: &Settings) -> &str {
    let d = settings.proxy.domain.trim();
    if d.is_empty() { "localhost" } else { d }
}

/// Certificate and key generated for the self-signed mode, one pair per domain.
pub fn self_signed_paths(settings: &Settings) -> (PathBuf, PathBuf) {
    let name: String = domain(settings)
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '.' || c == '-' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let dir = crate::config::config_dir().join("tls");
    (
        dir.join(format!("{name}.crt")),
        dir.join(format!("{name}.key")),
    )
}

/// KDL string literal.
fn quote(s: &str) -> String {
    format!(
        "\"{}\"",
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', "\\n")
    )
}

fn regex_escape(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if "\\.+*?()|[]{}^$#&-~".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// URL clients should use to reach the proxy.
pub fn public_url(settings: &Settings) -> String {
    let p = &settings.proxy;
    let domain = domain(settings);
    match p.tls {
        TlsMode::Off => format!("http://{domain}:{}", p.port),
        _ if p.port == 443 => format!("https://{domain}"),
        _ => format!("https://{domain}:{}", p.port),
    }
}

pub fn generate(settings: &Settings) -> String {
    let p = &settings.proxy;
    let upstream = settings.upstream_addr();
    let mut out = String::new();
    out.push_str("// Generated by llegion — changes are overwritten when settings are saved.\n");

    out.push_str("* {\n");
    if p.tls != TlsMode::Acme {
        // Only the configured port; ACME needs Ferron's default 80/443 listeners.
        out.push_str("    default_http_port #null\n    default_https_port #null\n");
    }
    let listen = p.listen_host.trim();
    if !listen.is_empty() && listen != "0.0.0.0" {
        out.push_str(&format!("    listen_ip {}\n", quote(listen)));
    }
    // Captured by the app and shown in the Logs tab.
    out.push_str("    log_stderr\n    error_log_stderr\n}\n\n");

    let site = match p.tls {
        TlsMode::Acme if p.port == 443 => domain(settings).to_string(),
        TlsMode::Acme => format!("{}:{}", domain(settings), p.port),
        _ => format!("*:{}", p.port),
    };
    out.push_str(&format!("{} {{\n", quote(&site)));
    match p.tls {
        TlsMode::Internal => {
            let (cert, key) = self_signed_paths(settings);
            out.push_str(&format!(
                "    tls {} {}\n",
                quote(&cert.display().to_string()),
                quote(&key.display().to_string())
            ));
        }
        TlsMode::Custom => out.push_str(&format!(
            "    tls {} {}\n",
            quote(p.cert_path.trim()),
            quote(p.key_path.trim())
        )),
        TlsMode::Acme => {
            out.push_str("    auto_tls\n");
            if !p.acme_email.trim().is_empty() {
                out.push_str(&format!(
                    "    auto_tls_contact {}\n",
                    quote(p.acme_email.trim())
                ));
            }
        }
        TlsMode::Off => {}
    }

    let tokens: Vec<&str> = p
        .tokens
        .iter()
        .map(|t| t.token.trim())
        .filter(|t| !t.is_empty())
        .collect();
    if p.require_token && tokens.is_empty() {
        out.push_str(
            "\n    // Token auth enabled but no token defined: deny everything.\n    status 401 body=\"Unauthorized\"\n}\n",
        );
        return out;
    }

    let cors = p.cors_origin.trim();
    if !cors.is_empty() {
        out.push_str(&format!(
            "\n    header \"Access-Control-Allow-Origin\" {}\n    header \"Access-Control-Allow-Headers\" \"Authorization, Content-Type\"\n    header \"Access-Control-Allow-Methods\" \"GET, POST, DELETE, OPTIONS\"\n",
            quote(cors)
        ));
        out.push_str(
            "    condition \"PREFLIGHT\" {\n        is_equal \"{method}\" \"OPTIONS\"\n    }\n",
        );
    }
    if p.require_token {
        // Conditions only AND their checks, so the tokens are alternatives in one regex.
        let alts: Vec<String> = tokens.iter().map(|t| regex_escape(t)).collect();
        out.push_str(&format!(
            "    condition \"AUTHORIZED\" {{\n        is_regex \"{{header:Authorization}}\" {}\n    }}\n",
            quote(&format!("^Bearer (?:{})$", alts.join("|")))
        ));
    }

    // Ollama rejects unknown Host headers when bound to loopback.
    out.push_str(&format!(
        "\n    proxy_request_header_replace \"Host\" {}\n",
        quote(&upstream)
    ));
    out.push_str("    proxy_request_header_remove \"Authorization\"\n");

    let proxy = format!("proxy {}", quote(&format!("http://{upstream}")));
    let mut indent = "    ";
    if !cors.is_empty() {
        out.push_str("    if \"PREFLIGHT\" {\n        status 204 body=\"\"\n    }\n");
        out.push_str("    if_not \"PREFLIGHT\" {\n");
        indent = "        ";
    }
    if p.require_token {
        out.push_str(&format!(
            "{indent}if \"AUTHORIZED\" {{\n{indent}    {proxy}\n{indent}}}\n{indent}if_not \"AUTHORIZED\" {{\n{indent}    status 401 body=\"Unauthorized\"\n{indent}}}\n"
        ));
    } else {
        out.push_str(&format!("{indent}{proxy}\n"));
    }
    if !cors.is_empty() {
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    out
}

/// Writes the configuration, plus a self-signed certificate when that mode needs one.
pub fn write(settings: &Settings) -> anyhow::Result<PathBuf> {
    if settings.proxy.tls == TlsMode::Internal {
        ensure_self_signed(settings)?;
    }
    let path = config_path();
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, generate(settings))?;
    // Contains the API tokens.
    crate::config::restrict_permissions(&path);
    Ok(path)
}

fn ensure_self_signed(settings: &Settings) -> anyhow::Result<()> {
    let (cert_path, key_path) = self_signed_paths(settings);
    if cert_path.exists() && key_path.exists() {
        return Ok(());
    }
    let mut names = vec![domain(settings).to_string()];
    for n in ["localhost", "127.0.0.1"] {
        if names[0] != n {
            names.push(n.into());
        }
    }
    write_self_signed(names, &cert_path, &key_path)
}

#[cfg(feature = "rustls")]
pub fn write_self_signed(
    names: Vec<String>,
    cert_path: &std::path::Path,
    key_path: &std::path::Path,
) -> anyhow::Result<()> {
    let cert = rcgen::generate_simple_self_signed(names)?;
    if let Some(dir) = cert_path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(key_path, cert.signing_key.serialize_pem())?;
    crate::config::restrict_permissions(key_path);
    std::fs::write(cert_path, cert.cert.pem())?;
    Ok(())
}

#[cfg(not(feature = "rustls"))]
pub fn write_self_signed(
    _names: Vec<String>,
    _cert_path: &std::path::Path,
    _key_path: &std::path::Path,
) -> anyhow::Result<()> {
    anyhow::bail!("self-signed certificates need a build with the `rustls` feature")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::ApiToken;

    fn settings(tls: TlsMode) -> Settings {
        let mut s = Settings::default();
        s.proxy.enabled = true;
        s.proxy.tls = tls;
        s.proxy.domain = "ollama.lan".into();
        s.proxy.tokens = vec![
            ApiToken {
                label: "a".into(),
                token: "tok1".into(),
            },
            ApiToken {
                label: "b".into(),
                token: "t.k+2".into(),
            },
        ];
        s
    }

    #[test]
    fn internal_tls_with_tokens() {
        let c = generate(&settings(TlsMode::Internal));
        assert!(c.contains("\"*:8443\" {"));
        assert!(c.contains("ollama.lan.crt"));
        assert!(c.contains("default_https_port #null"));
        assert!(c.contains(r#"is_regex "{header:Authorization}" "^Bearer (?:tok1|t\\.k\\+2)$""#));
        assert!(c.contains("    if \"AUTHORIZED\" {\n        proxy \"http://127.0.0.1:11434\""));
        assert!(c.contains("proxy_request_header_remove \"Authorization\""));
        assert!(!c.contains("PREFLIGHT"));
    }

    #[test]
    fn no_tokens_denies_everything() {
        let mut s = settings(TlsMode::Off);
        s.proxy.tokens.clear();
        let c = generate(&s);
        assert!(c.contains("status 401"));
        assert!(!c.contains("proxy "));
        assert!(!c.contains("tls "));
    }

    #[test]
    fn cors_skips_auth_for_preflight() {
        let mut s = settings(TlsMode::Acme);
        s.proxy.port = 443;
        s.proxy.acme_email = "me@example.com".into();
        s.proxy.cors_origin = "https://chat.example.com".into();
        let c = generate(&s);
        assert!(c.contains("\n\"ollama.lan\" {\n    auto_tls\n"));
        assert!(c.contains("auto_tls_contact \"me@example.com\""));
        assert!(!c.contains("default_https_port"));
        assert!(c.contains("if_not \"PREFLIGHT\" {\n        if \"AUTHORIZED\""));
        assert_eq!(public_url(&s), "https://ollama.lan");
    }

    #[test]
    fn without_token_check_proxies_directly() {
        let mut s = settings(TlsMode::Custom);
        s.proxy.require_token = false;
        s.proxy.cert_path = "/c.pem".into();
        s.proxy.key_path = "/k.pem".into();
        let c = generate(&s);
        assert!(c.contains("tls \"/c.pem\" \"/k.pem\""));
        assert!(c.contains("\n    proxy \"http://127.0.0.1:11434\"\n}"));
        assert!(!c.contains("AUTHORIZED"));
    }
}
