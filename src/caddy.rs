//! Caddyfile generation for exposing Ollama over HTTPS with bearer-token auth.

use std::path::PathBuf;

use crate::config::{Settings, TlsMode};

pub fn caddyfile_path() -> PathBuf {
    crate::config::config_dir().join("Caddyfile")
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub fn site_address(settings: &Settings) -> String {
    let p = &settings.proxy;
    let domain = if p.domain.trim().is_empty() {
        "localhost"
    } else {
        p.domain.trim()
    };
    match p.tls {
        TlsMode::Off => format!("http://:{}", p.port),
        TlsMode::Acme if p.port == 443 => domain.to_string(),
        _ => format!("https://{domain}:{}", p.port),
    }
}

/// URL clients should use to reach the proxy.
pub fn public_url(settings: &Settings) -> String {
    let p = &settings.proxy;
    let domain = if p.domain.trim().is_empty() {
        "localhost"
    } else {
        p.domain.trim()
    };
    match p.tls {
        TlsMode::Off => format!("http://{domain}:{}", p.port),
        _ if p.port == 443 => format!("https://{domain}"),
        _ => format!("https://{domain}:{}", p.port),
    }
}

pub fn generate(settings: &Settings) -> String {
    let p = &settings.proxy;
    let upstream = settings.upstream_addr();
    let mut out = String::new();
    out.push_str("# Generated by ollama-egui — changes are overwritten when settings are saved.\n");
    out.push_str("{\n\tadmin off\n");
    if p.tls == TlsMode::Acme && !p.acme_email.trim().is_empty() {
        out.push_str(&format!("\temail {}\n", p.acme_email.trim()));
    }
    if p.tls != TlsMode::Acme {
        out.push_str("\tauto_https disable_redirects\n");
    }
    out.push_str("}\n\n");

    out.push_str(&format!("{} {{\n", site_address(settings)));
    if !p.listen_host.trim().is_empty() && p.listen_host.trim() != "0.0.0.0" {
        out.push_str(&format!("\tbind {}\n", p.listen_host.trim()));
    }
    match p.tls {
        TlsMode::Internal => out.push_str("\ttls internal\n"),
        TlsMode::Custom => out.push_str(&format!(
            "\ttls {} {}\n",
            quote(p.cert_path.trim()),
            quote(p.key_path.trim())
        )),
        TlsMode::Acme | TlsMode::Off => {}
    }
    out.push_str("\tencode gzip\n\n");

    let cors = p.cors_origin.trim();
    if !cors.is_empty() {
        out.push_str(&format!(
            "\theader {{\n\t\tAccess-Control-Allow-Origin {}\n\t\tAccess-Control-Allow-Headers \"Authorization, Content-Type\"\n\t\tAccess-Control-Allow-Methods \"GET, POST, DELETE, OPTIONS\"\n\t}}\n",
            quote(cors)
        ));
        out.push_str("\t@preflight method OPTIONS\n\trespond @preflight 204\n\n");
    }

    let tokens: Vec<&str> = p
        .tokens
        .iter()
        .map(|t| t.token.trim())
        .filter(|t| !t.is_empty())
        .collect();
    if p.require_token {
        if tokens.is_empty() {
            out.push_str(
                "\t# Token auth enabled but no token defined: deny everything.\n\trespond 401\n}\n",
            );
            return out;
        }
        let values: Vec<String> = tokens
            .iter()
            .map(|t| quote(&format!("Bearer {t}")))
            .collect();
        out.push_str(&format!(
            "\t@unauthorized {{\n\t\tnot header Authorization {}\n",
            values.join(" ")
        ));
        if !cors.is_empty() {
            out.push_str("\t\tnot method OPTIONS\n");
        }
        out.push_str("\t}\n");
        out.push_str("\trespond @unauthorized \"Unauthorized\" 401\n\n");
    }

    out.push_str(&format!("\treverse_proxy {upstream} {{\n"));
    // Ollama rejects unknown Host headers when bound to loopback.
    out.push_str(&format!("\t\theader_up Host {upstream}\n"));
    out.push_str("\t\theader_up -Authorization\n");
    // Stream tokens to the client as soon as they are produced.
    out.push_str("\t\tflush_interval -1\n");
    out.push_str("\t}\n}\n");
    out
}

pub fn write(settings: &Settings) -> anyhow::Result<PathBuf> {
    let path = caddyfile_path();
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, generate(settings))?;
    // Contains the API tokens.
    crate::config::restrict_permissions(&path);
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::ApiToken;

    fn settings(tls: TlsMode) -> Settings {
        let mut s = Settings::default();
        s.proxy.enabled = true;
        s.proxy.tls = tls;
        s.proxy.domain = "ollama.lan".into();
        s.proxy.tokens = vec![
            ApiToken {
                label: "a".into(),
                token: "tok1".into(),
            },
            ApiToken {
                label: "b".into(),
                token: "tok2".into(),
            },
        ];
        s
    }

    #[test]
    fn internal_tls_with_tokens() {
        let c = generate(&settings(TlsMode::Internal));
        assert!(c.contains("https://ollama.lan:8443 {"));
        assert!(c.contains("tls internal"));
        assert!(c.contains(r#"not header Authorization "Bearer tok1" "Bearer tok2""#));
        assert!(c.contains("reverse_proxy 127.0.0.1:11434"));
        assert!(c.contains("header_up -Authorization"));
        assert!(!c.contains("not method OPTIONS"));
    }

    #[test]
    fn no_tokens_denies_everything() {
        let mut s = settings(TlsMode::Off);
        s.proxy.tokens.clear();
        let c = generate(&s);
        assert!(c.contains("respond 401"));
        assert!(!c.contains("reverse_proxy"));
    }

    #[test]
    fn cors_skips_auth_for_preflight() {
        let mut s = settings(TlsMode::Acme);
        s.proxy.port = 443;
        s.proxy.cors_origin = "https://chat.example.com".into();
        let c = generate(&s);
        assert!(c.contains("\nollama.lan {"));
        assert!(c.contains("not method OPTIONS"));
        assert_eq!(public_url(&s), "https://ollama.lan");
    }
}
